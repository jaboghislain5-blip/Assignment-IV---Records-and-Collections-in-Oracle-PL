-- Drop existing tables to ensure clean setup (in reverse dependency order)
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE treatments CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE appointments CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE doctors CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE patients CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- 1. Patients Table
CREATE TABLE patients (
    patient_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR2(50) NOT NULL,
    last_name     VARCHAR2(50) NOT NULL,
    dob           DATE NOT NULL,
    gender        VARCHAR2(10) CHECK (gender IN ('Male', 'Female', 'Other')),
    phone         VARCHAR2(20),
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- 2. Doctors Table
CREATE TABLE doctors (
    doctor_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name        VARCHAR2(50) NOT NULL,
    last_name         VARCHAR2(50) NOT NULL,
    specialization    VARCHAR2(100) NOT NULL,
    consultation_fee  NUMBER(10, 2) NOT NULL,
    status            VARCHAR2(20) DEFAULT 'Active' CHECK (status IN ('Active', 'On Leave'))
);

-- 3. Appointments Table
CREATE TABLE appointments (
    appointment_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id        NUMBER REFERENCES patients(patient_id) ON DELETE CASCADE,
    doctor_id         NUMBER REFERENCES doctors(doctor_id) ON DELETE SET NULL,
    appointment_date  DATE NOT NULL,
    status            VARCHAR2(20) DEFAULT 'Scheduled' CHECK (status IN ('Scheduled', 'Completed', 'Cancelled'))
);

-- 4. Treatments Table
CREATE TABLE treatments (
    treatment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id    NUMBER REFERENCES appointments(appointment_id) ON DELETE CASCADE,
    treatment_name    VARCHAR2(100) NOT NULL,
    cost              NUMBER(10, 2) NOT NULL,
    treatment_date    DATE DEFAULT SYSDATE
);

COMMIT;